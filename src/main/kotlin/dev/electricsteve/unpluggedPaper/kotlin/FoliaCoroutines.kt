package dev.electricsteve.unpluggedPaper.kotlin

import kotlinx.coroutines.*
import org.bukkit.Location
import org.bukkit.entity.Entity
import org.bukkit.plugin.Plugin
import org.slf4j.LoggerFactory
import java.lang.Runnable
import java.util.concurrent.CompletableFuture
import java.util.concurrent.RejectedExecutionException
import kotlin.coroutines.CoroutineContext
import kotlin.coroutines.resume
import kotlin.coroutines.resumeWithException

/*
* This is a Kotlin adapter for Folia's coroutine support. It provides a way to run coroutines in the context of a Bukkit plugin, with support for running tasks at specific locations or on specific entities.
* For full transparency: this code was generated by an AI, because my kotlin is ass, especially with coroutines. I did check the code and it seems fine.
*/
object FoliaCoroutines {
    private val scope = CoroutineScope(SupervisorJob())

    @JvmStatic
    fun global(plugin: Plugin): CoroutineDispatcher =
        Dispatcher(plugin)

    @JvmStatic
    fun at(plugin: Plugin, location: Location): CoroutineDispatcher =
        Dispatcher(plugin, location = location)

    @JvmStatic
    fun on(plugin: Plugin, entity: Entity): CoroutineDispatcher =
        Dispatcher(plugin, entity = entity)

    /**
     * Called by small Kotlin adapters for individual suspend API methods.
     */
    fun <T> run(
        dispatcher: CoroutineDispatcher,
        task: suspend () -> T
    ): CompletableFuture<T> {
        val future = CompletableFuture<T>()

        scope.launch(dispatcher, start = CoroutineStart.DEFAULT) {
            try {
                future.complete(task())
            } catch (t: Throwable) {
                LoggerFactory.getLogger("FoliaCoroutines").error("Error in coroutine", t)
                future.completeExceptionally(t)
            }
        }

        return future
    }

    @OptIn(InternalCoroutinesApi::class)
    private class Dispatcher(
        private val plugin: Plugin,
        private val location: Location? = null,
        private val entity: Entity? = null
    ) : CoroutineDispatcher(), Delay {

        private fun ticks(milliseconds: Long): Long =
            ((milliseconds + 49) / 50).coerceAtLeast(1)

        override fun dispatch(context: CoroutineContext, block: Runnable) {
            when {
                entity != null -> {
                    if (!entity.isValid) {
                        throw RejectedExecutionException("Entity is invalid")
                    }

                    entity.scheduler.run(
                        plugin,
                        { block.run() },
                        { throw RejectedExecutionException("Task retired") }
                    )
                }

                location != null ->
                    plugin.server.regionScheduler.execute(plugin, location, block)

                else ->
                    plugin.server.globalRegionScheduler.execute(plugin, block)
            }
        }

        override fun scheduleResumeAfterDelay(
            timeMillis: Long,
            continuation: CancellableContinuation<Unit>
        ) {
            val delay = ticks(timeMillis)

            when {
                entity != null -> {
                    if (!entity.isValid) {
                        continuation.resumeWithException(
                            RejectedExecutionException("Entity is invalid")
                        )
                        return
                    }

                    val task = entity.scheduler.runDelayed(
                        plugin,
                        { continuation.resume(Unit) },
                        {
                            if (continuation.isActive) {
                                continuation.resumeWithException(
                                    RejectedExecutionException("Task retired")
                                )
                            }
                        },
                        delay
                    )

                    continuation.invokeOnCancellation {
                        task?.cancel()
                    }
                }

                location != null -> {
                    val task = plugin.server.regionScheduler.runDelayed(
                        plugin,
                        location,
                        { continuation.resume(Unit) },
                        delay
                    )

                    continuation.invokeOnCancellation {
                        task.cancel()
                    }
                }

                else -> {
                    val task = plugin.server.globalRegionScheduler.runDelayed(
                        plugin,
                        { continuation.resume(Unit) },
                        delay
                    )

                    continuation.invokeOnCancellation {
                        task.cancel()
                    }
                }
            }
        }

        override fun invokeOnTimeout(
            timeMillis: Long,
            block: Runnable,
            context: CoroutineContext
        ): DisposableHandle {
            val delay = ticks(timeMillis)

            return when {
                entity != null -> {
                    if (!entity.isValid) {
                        DisposableHandle {}
                    } else {
                        val task = entity.scheduler.runDelayed(
                            plugin,
                            { block.run() },
                            null,
                            delay
                        )
                        DisposableHandle { task?.cancel() }
                    }
                }

                location != null -> {
                    val task = plugin.server.regionScheduler.runDelayed(
                        plugin,
                        location,
                        { block.run() },
                        delay
                    )
                    DisposableHandle { task.cancel() }
                }

                else -> {
                    val task = plugin.server.globalRegionScheduler.runDelayed(
                        plugin,
                        { block.run() },
                        delay
                    )
                    DisposableHandle { task.cancel() }
                }
            }
        }
    }
}